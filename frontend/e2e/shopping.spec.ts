test('reply dialog keeps keyboard focus and returns to the repaired plan', async ({page}) => {
  await page.goto('/')
  await page.getByRole('button',{name:'دیدن سناریوی نمونه'}).click()
  const trigger=page.getByTestId('primary-card').getByRole('button',{name:'بررسی پاسخ فروشنده'})
  await trigger.click()
  const dialog=page.getByRole('dialog',{name:'بررسی پاسخ فروشنده'})
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('متن پاسخ فروشنده')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await dialog.getByRole('button',{name:'پیش‌نمایش تغییر'}).click()
  await dialog.getByRole('button',{name:'تأیید پاسخ و بازچینی'}).click()
  await expect(dialog).toBeHidden()
  await expect(page.locator('#mission')).toBeFocused()
  await expect(page.getByTestId('plan-delta')).toBeInViewport()
})

test('cancel during initial AI request prevents a late answer from replacing search', async ({page}) => {
  await page.goto('/')
  // Controlled delayed transport; the actual server is deliberately not asked to infer here.
  let release!:()=>void
  const held=new Promise<void>(resolve=>{release=resolve})
  await page.route('**/api/capabilities',route=>route.fulfill({json:{catalogue_ready:true,model_available:true}}))
  await page.reload()
  await page.route('**/api/turns',async route=>{await held;await route.fulfill({json:{id:'late-test',state:'completed',stage:'interpret',result:{products:[],recommendations:[],clarification_fa:'LATE_RESPONSE_SHOULD_NOT_RENDER',proposed_constraints:{}}}})})
  await page.route('**/api/turns/late-test/cancel',route=>route.fulfill({json:{state:'canceled'}}))
  await page.getByLabel('نیاز شما').fill('گوشی برای کار روزمره')
  await page.getByRole('button',{name:'کمک برای انتخاب'}).click()
  await expect(page.getByRole('button',{name:'توقف بررسی'})).toBeVisible()
  await page.getByRole('button',{name:'توقف بررسی'}).click()
  release()
  await expect(page.getByText('LATE_RESPONSE_SHOULD_NOT_RENDER')).toHaveCount(0)
  await page.locator('.manual-search>summary').click()
  await page.getByLabel('جست‌وجوی کالا').fill('A07')
  await page.getByRole('button',{name:'جست‌وجو',exact:true}).click()
  await expect(page.getByTestId('product-card').first()).toBeVisible()
})

